
-- =========================================================
-- 1. ORGANIZZAZIONI
-- =========================================================

CREATE TABLE organizations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'suspended', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 2. UTENTI
-- =========================================================

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'disabled')),
    email_verified_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX users_email_unique
    ON users (LOWER(email));

-- =========================================================
-- 3. APPARTENENZA E RUOLI
-- =========================================================

CREATE TABLE memberships (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL
        REFERENCES organizations(id) ON DELETE CASCADE,
    user_id UUID NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('admin', 'editor', 'analyst', 'viewer')),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'suspended')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (organization_id, user_id),
    UNIQUE (organization_id, id)
);

CREATE INDEX memberships_user_idx
    ON memberships(user_id);

-- =========================================================
-- 4. INVITI
-- =========================================================

CREATE TABLE invitations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL
        REFERENCES organizations(id) ON DELETE CASCADE,
    email VARCHAR(254) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('admin', 'editor', 'analyst', 'viewer')),
    token_hash TEXT NOT NULL UNIQUE,
    invited_by UUID NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX invitations_org_email_idx
    ON invitations(organization_id, LOWER(email));

CREATE INDEX invitations_expiry_idx
    ON invitations(expires_at);

-- =========================================================
-- 5. SESSIONI
-- =========================================================

CREATE TABLE sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX sessions_user_idx
    ON sessions(user_id);

CREATE INDEX sessions_expiry_idx
    ON sessions(expires_at);

-- =========================================================
-- 6. FASI DEL FUNNEL
-- =========================================================

CREATE TABLE funnel_stages (
    organization_id UUID NOT NULL
        REFERENCES organizations(id) ON DELETE CASCADE,
    id VARCHAR(80) NOT NULL,
    label VARCHAR(50) NOT NULL,
    position INTEGER NOT NULL CHECK (position >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, position)
);

CREATE INDEX funnel_stages_position_idx
    ON funnel_stages(organization_id, position);

-- =========================================================
-- 7. CLIENTI
-- =========================================================

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id UUID NOT NULL
        REFERENCES organizations(id) ON DELETE CASCADE,
    channel TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    UNIQUE (organization_id, id)
);

CREATE INDEX customers_org_created_idx
    ON customers(organization_id, created_at);

CREATE INDEX customers_org_channel_idx
    ON customers(organization_id, channel);

-- =========================================================
-- 8. EVENTI DEL CUSTOMER JOURNEY
-- =========================================================

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id UUID NOT NULL,
    customer_id BIGINT NOT NULL,
    stage_id VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,

    FOREIGN KEY (organization_id, customer_id)
        REFERENCES customers(organization_id, id)
        ON DELETE CASCADE,

    FOREIGN KEY (organization_id, stage_id)
        REFERENCES funnel_stages(organization_id, id)
        ON DELETE RESTRICT
);

CREATE INDEX events_org_customer_stage_idx
    ON events(organization_id, customer_id, stage_id);

CREATE INDEX events_org_occurred_idx
    ON events(organization_id, occurred_at);

-- =========================================================
-- 9. IMPORTAZIONI
-- =========================================================

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id UUID NOT NULL
        REFERENCES organizations(id) ON DELETE CASCADE,
    fingerprint TEXT NOT NULL,
    file_name TEXT NOT NULL,
    customer_count INTEGER NOT NULL CHECK (customer_count >= 0),
    row_count INTEGER NOT NULL CHECK (row_count >= 0),
    imported_by UUID
        REFERENCES users(id) ON DELETE SET NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (organization_id, fingerprint)
);

CREATE INDEX import_batches_org_date_idx
    ON import_batches(organization_id, imported_at DESC);

-- =========================================================
-- 10. AUDIT LOG
-- =========================================================

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id UUID
        REFERENCES organizations(id) ON DELETE SET NULL,
    actor_user_id UUID
        REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(100),
    resource_id TEXT,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    ip_address INET,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX audit_logs_org_date_idx
    ON audit_logs(organization_id, created_at DESC);

CREATE INDEX audit_logs_actor_idx
    ON audit_logs(actor_user_id, created_at DESC);

