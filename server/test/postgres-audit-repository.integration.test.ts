import { afterAll, describe, expect, it, vi } from "vitest";
import { Pool } from "pg";
import { listPostgresAuditLogs } from "../src/postgres-audit-repository.js";

const connectionString = process.env.DATABASE_URL;
const pool = connectionString
  ? new Pool({ connectionString, max: 1, connectionTimeoutMillis: 5_000 })
  : null;

afterAll(async () => { await pool?.end(); });

describe("PostgreSQL audit repository", () => {
  it.skipIf(!pool)("filtra per tenant, utente, operazione e date e pagina in ordine decrescente", async () => {
    const organizationA = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
    const organizationB = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
    const actorA = "11111111-1111-4111-8111-111111111111";
    const actorB = "22222222-2222-4222-8222-222222222222";
    const client = await pool!.connect();
    try {
      await client.query(`
        CREATE TEMP TABLE users (
          id UUID PRIMARY KEY,
          full_name TEXT NOT NULL,
          email TEXT NOT NULL
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(`
        CREATE TEMP TABLE audit_logs (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          organization_id UUID NOT NULL,
          actor_user_id UUID,
          action TEXT NOT NULL,
          resource_type TEXT,
          resource_id TEXT,
          details JSONB NOT NULL DEFAULT '{}'::jsonb,
          created_at TIMESTAMPTZ NOT NULL
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(
        `INSERT INTO users (id, full_name, email) VALUES
         ($1, 'Admin Uno', 'admin1@example.test'),
         ($2, 'Admin Due', 'admin2@example.test')`,
        [actorA, actorB],
      );
      await client.query(
        `INSERT INTO audit_logs
          (organization_id, actor_user_id, action, resource_type, resource_id, details, created_at)
         VALUES
          ($1, $2, 'customer.created', 'customer', '10', '{"channel":"Organico"}', '2026-11-10T10:00:00Z'),
          ($1, $2, 'customer.updated', 'customer', '10', '{"channel":"Social"}', '2026-11-11T10:00:00Z'),
          ($1, $3, 'customer.created', 'customer', '11', '{}', '2026-11-12T10:00:00Z'),
          ($4, $3, 'customer.deleted', 'customer', '20', '{}', '2026-11-12T12:00:00Z')`,
        [organizationA, actorA, actorB, organizationB],
      );
    } finally {
      client.release();
    }

    const filtered = await listPostgresAuditLogs(pool!, organizationA, {
      page: 1, limit: 10, from: "2026-11-10", to: "2026-11-11",
      actorUserId: actorA, action: "customer.created",
    });
    expect(filtered.pagination).toEqual({ page: 1, limit: 10, total: 1, totalPages: 1 });
    expect(filtered.data).toHaveLength(1);
    expect(filtered.data[0]).toMatchObject({
      action: "customer.created",
      resourceType: "customer",
      resourceId: "10",
      actorUserId: actorA,
      actorName: "Admin Uno",
      actorEmail: "admin1@example.test",
      details: { channel: "Organico" },
    });

    const firstPage = await listPostgresAuditLogs(pool!, organizationA, { page: 1, limit: 1 });
    expect(firstPage.pagination.total).toBe(3);
    expect(firstPage.pagination.totalPages).toBe(3);
    expect(firstPage.data[0]?.action).toBe("customer.created");
    expect(firstPage.data[0]?.actorName).toBe("Admin Due");

    const secondPage = await listPostgresAuditLogs(pool!, organizationA, { page: 2, limit: 1 });
    expect(secondPage.data[0]?.action).toBe("customer.updated");

    const tenantB = await listPostgresAuditLogs(pool!, organizationB, { page: 1, limit: 10 });
    expect(tenantB.pagination.total).toBe(1);
    expect(tenantB.data[0]?.action).toBe("customer.deleted");
  });

  it("rifiuta paginazione non valida prima di aprire una connessione", async () => {
    const connect = vi.fn();
    await expect(listPostgresAuditLogs({ connect } as never, "org", { page: 0, limit: 10 }))
      .rejects.toThrow("Parametri di paginazione audit non validi.");
    expect(connect).not.toHaveBeenCalled();
  });
});
