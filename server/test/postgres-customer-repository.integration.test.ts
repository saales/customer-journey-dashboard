import { afterAll, describe, expect, it } from "vitest";
import { Pool } from "pg";
import { createPostgresCustomer, deletePostgresCustomer, listPostgresCustomers, updatePostgresCustomer } from "../src/postgres-customer-repository.js";

const connectionString = process.env.DATABASE_URL;
const pool = connectionString
  ? new Pool({ connectionString, max: 1, connectionTimeoutMillis: 5_000 })
  : null;

afterAll(async () => {
  await pool?.end();
});

describe("PostgreSQL customer repository", () => {
  it.skipIf(!pool)("isola conteggi, pagine ed eventi per tenant e ripulisce il contesto locale", async () => {
    const organizationA = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
    const organizationB = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
    const client = await pool!.connect();

    try {
      await client.query(`
        CREATE TEMP TABLE customers (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          organization_id UUID NOT NULL,
          external_id TEXT,
          channel TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(`
        CREATE TEMP TABLE funnel_stages (
          organization_id UUID NOT NULL,
          id TEXT NOT NULL,
          position INTEGER NOT NULL,
          is_active BOOLEAN NOT NULL DEFAULT TRUE,
          PRIMARY KEY (organization_id, id)
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(`
        CREATE TEMP TABLE audit_logs (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          organization_id UUID NOT NULL,
          actor_user_id UUID NOT NULL,
          action TEXT NOT NULL,
          resource_type TEXT NOT NULL,
          resource_id TEXT NOT NULL,
          details JSONB NOT NULL DEFAULT '{}'::jsonb
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(`
        CREATE TEMP TABLE events (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          organization_id UUID NOT NULL,
          customer_id BIGINT NOT NULL,
          stage_id TEXT NOT NULL,
          occurred_at TIMESTAMPTZ NOT NULL
        ) ON COMMIT PRESERVE ROWS
      `);
      await client.query(
        `INSERT INTO customers (id, organization_id, channel, created_at)
         VALUES
           (101, $1, 'organic', '2026-01-02T00:00:00Z'),
           (102, $1, 'paid', '2026-01-03T00:00:00Z'),
           (201, $2, 'partner', '2026-01-04T00:00:00Z')`,
        [organizationA, organizationB],
      );
      await client.query(
        `INSERT INTO events (id, organization_id, customer_id, stage_id, occurred_at)
         VALUES
           (1001, $1, 101, 'visit', '2026-01-02T00:00:00Z'),
           (1002, $1, 101, 'lead', '2026-01-02T12:00:00Z'),
           (2001, $2, 201, 'visit', '2026-01-04T00:00:00Z')`,
        [organizationA, organizationB],
      );
    } finally {
      client.release();
    }

    const firstPage = await listPostgresCustomers(pool!, organizationA, 1, 1);
    expect(firstPage).toEqual({
      data: [{
        id: "102",
        channel: "paid",
        createdAt: "2026-01-03",
        events: [],
      }],
      pagination: { page: 1, limit: 1, total: 2, totalPages: 2 },
    });

    const secondPage = await listPostgresCustomers(pool!, organizationA, 2, 1);
    expect(secondPage.data).toEqual([{
      id: "101",
      channel: "organic",
      createdAt: "2026-01-02",
      events: [
        { stage: "visit", occurredAt: "2026-01-02" },
        { stage: "lead", occurredAt: "2026-01-02" },
      ],
    }]);

    const tenantB = await listPostgresCustomers(pool!, organizationB);
    expect(tenantB.data.map((customer) => customer.id)).toEqual(["201"]);
    expect(tenantB.pagination.total).toBe(1);

    const after = await pool!.query<{ tenant: string | null }>(
      "SELECT current_setting('app.organization_id', true) AS tenant",
    );
    expect(after.rows[0]?.tenant).not.toBe(organizationA);
    expect(after.rows[0]?.tenant).not.toBe(organizationB);
  });


  it.skipIf(!pool)("crea cliente ed eventi in modo atomico e tenant-scoped", async () => {
    const organizationId = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
    const client = await pool!.connect();
    try {
      await client.query(
        `INSERT INTO funnel_stages (organization_id, id, position)
         VALUES ($1, 'visit', 0), ($1, 'lead', 1), ($1, 'customer', 2)
         ON CONFLICT (organization_id, id) DO UPDATE SET position = EXCLUDED.position, is_active = TRUE`,
        [organizationId],
      );
    } finally {
      client.release();
    }

    const actorUserId = "99999999-9999-4999-8999-999999999999";
    const created = await createPostgresCustomer(pool!, organizationId, {
      externalId: "crm-100",
      channel: "Organico",
      createdAt: "2026-04-01",
      events: [
        { stage: "visit", occurredAt: "2026-04-01" },
        { stage: "lead", occurredAt: "2026-04-02" },
      ],
    }, actorUserId);
    expect(created).toMatchObject({ externalId: "crm-100" });
    expect(created.id).toMatch(/^\d+$/);

    const listed = await listPostgresCustomers(pool!, organizationId);
    expect(listed.data).toContainEqual({
      id: created.id,
      channel: "Organico",
      createdAt: "2026-04-01",
      events: [
        { stage: "visit", occurredAt: "2026-04-01" },
        { stage: "lead", occurredAt: "2026-04-02" },
      ],
    });

    await expect(createPostgresCustomer(pool!, organizationId, {
      externalId: "crm-101",
      channel: "Organico",
      createdAt: "2026-04-01",
      events: [{ stage: "lead", occurredAt: "2026-04-02" }],
    })).rejects.toThrow("Il percorso deve iniziare con la fase visit.");

    const count = await pool!.query<{ count: string }>(
      "SELECT COUNT(*)::text AS count FROM customers WHERE organization_id = $1::uuid",
      [organizationId],
    );
    expect(Number(count.rows[0]?.count)).toBe(1);

    const updated = await updatePostgresCustomer(pool!, organizationId, created.id, {
      externalId: "crm-100", channel: "Social", createdAt: "2026-04-01",
      events: [{ stage: "visit", occurredAt: "2026-04-01" }, { stage: "lead", occurredAt: "2026-04-03" }],
    }, actorUserId);
    expect(updated).toMatchObject({ id: created.id, channel: "Social" });
    expect((await listPostgresCustomers(pool!, organizationId)).data[0]?.events).toEqual([
      { stage: "visit", occurredAt: "2026-04-01" }, { stage: "lead", occurredAt: "2026-04-03" },
    ]);
    await expect(updatePostgresCustomer(pool!, organizationId, "999999", {
      externalId: "crm-999", channel: "Social", createdAt: "2026-04-01",
      events: [{ stage: "visit", occurredAt: "2026-04-01" }],
    })).rejects.toThrow("Cliente non trovato.");
    await deletePostgresCustomer(pool!, organizationId, created.id, actorUserId);
    expect((await listPostgresCustomers(pool!, organizationId)).pagination.total).toBe(0);
    const audit = await pool!.query<{ action: string }>("SELECT action FROM audit_logs ORDER BY id");
    expect(audit.rows.map((row) => row.action)).toEqual([
      "customer.created", "customer.updated", "customer.deleted",
    ]);

  });

  it("rejects invalid tenant identifiers and pagination before connecting", async () => {
    const invalidPool = { connect: () => { throw new Error("must not connect"); } };
    await expect(listPostgresCustomers(invalidPool, "not-a-uuid")).rejects.toThrow(
      "Identificativo organizzazione non valido.",
    );
    await expect(listPostgresCustomers(invalidPool, "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", 0))
      .rejects.toThrow("Parametro page non valido.");
    await expect(listPostgresCustomers(invalidPool, "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", 1, 101))
      .rejects.toThrow("Parametro limit non valido");
  });

  it.skipIf(!pool)("rolls back customer writes when the audit insert fails", async () => {
    const organizationId = "abababab-abab-4bab-8bab-abababababab";
    const actorUserId = "99999999-9999-4999-8999-999999999999";
    const client = await pool!.connect();
    try {
      await client.query("DROP TABLE IF EXISTS pg_temp.audit_logs, pg_temp.events, pg_temp.customers, pg_temp.funnel_stages CASCADE");
      await client.query(`CREATE TEMP TABLE funnel_stages (
        organization_id UUID NOT NULL, id TEXT NOT NULL, position INTEGER NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE, PRIMARY KEY (organization_id,id)
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(`CREATE TEMP TABLE customers (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID NOT NULL, external_id TEXT NOT NULL, channel TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL, UNIQUE (organization_id,external_id)
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(`CREATE TEMP TABLE events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID NOT NULL, customer_id BIGINT NOT NULL,
        stage_id TEXT NOT NULL, occurred_at TIMESTAMPTZ NOT NULL
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(`CREATE TEMP TABLE audit_logs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID NOT NULL, actor_user_id UUID NOT NULL,
        action TEXT NOT NULL CHECK (action NOT IN ('customer.created','customer.updated','customer.deleted')),
        resource_type TEXT NOT NULL, resource_id TEXT NOT NULL,
        details JSONB NOT NULL DEFAULT '{}'::jsonb
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(
        "INSERT INTO funnel_stages (organization_id,id,position) VALUES ($1,'visit',0),($1,'lead',1),($1,'customer',2)",
        [organizationId],
      );
    } finally {
      client.release();
    }

    const initialInput = {
      externalId: "audit-rollback-customer",
      channel: "Organico",
      createdAt: "2026-05-01",
      events: [{ stage: "visit", occurredAt: "2026-05-01" }],
    };

    await expect(createPostgresCustomer(pool!, organizationId, initialInput, actorUserId)).rejects.toThrow();
    let counts = await pool!.query<{ customers: string; events: string }>(
      "SELECT (SELECT COUNT(*)::text FROM customers WHERE organization_id=$1::uuid) AS customers, (SELECT COUNT(*)::text FROM events WHERE organization_id=$1::uuid) AS events",
      [organizationId],
    );
    expect(counts.rows[0]).toEqual({ customers: "0", events: "0" });

    // Create a baseline without an actor so no audit row is attempted.
    const baseline = await createPostgresCustomer(pool!, organizationId, initialInput);
    await expect(updatePostgresCustomer(pool!, organizationId, baseline.id, {
      ...initialInput,
      channel: "Social",
      events: [
        { stage: "visit", occurredAt: "2026-05-01" },
        { stage: "lead", occurredAt: "2026-05-02" },
      ],
    }, actorUserId)).rejects.toThrow();

    const unchanged = await listPostgresCustomers(pool!, organizationId);
    expect(unchanged.data[0]).toMatchObject({
      id: baseline.id,
      channel: "Organico",
      events: [{ stage: "visit", occurredAt: "2026-05-01" }],
    });

    await expect(deletePostgresCustomer(pool!, organizationId, baseline.id, actorUserId)).rejects.toThrow();
    counts = await pool!.query<{ customers: string; events: string }>(
      "SELECT (SELECT COUNT(*)::text FROM customers WHERE organization_id=$1::uuid) AS customers, (SELECT COUNT(*)::text FROM events WHERE organization_id=$1::uuid) AS events",
      [organizationId],
    );
    expect(counts.rows[0]).toEqual({ customers: "1", events: "1" });
  });


  it.skipIf(!pool)("preserves unchanged history on deactivated funnel stages during customer edits", async () => {
    const organizationId = "abababab-abab-4bab-8bab-abababababab";
    const client = await pool!.connect();
    try {
      await client.query("DROP TABLE IF EXISTS pg_temp.events, pg_temp.customers, pg_temp.funnel_stages CASCADE");
      await client.query(`CREATE TEMP TABLE funnel_stages (
        organization_id UUID NOT NULL,id TEXT NOT NULL,position INTEGER NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,PRIMARY KEY(organization_id,id)
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(`CREATE TEMP TABLE customers (
        id BIGINT PRIMARY KEY,organization_id UUID NOT NULL,external_id TEXT NOT NULL,
        channel TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(`CREATE TEMP TABLE events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID NOT NULL,customer_id BIGINT NOT NULL,
        stage_id TEXT NOT NULL,occurred_at TIMESTAMPTZ NOT NULL
      ) ON COMMIT PRESERVE ROWS`);
      await client.query(
        "INSERT INTO funnel_stages(organization_id,id,position,is_active) VALUES($1,'visit',0,TRUE),($1,'custom_demo',1,FALSE),($1,'customer',2,TRUE)",
        [organizationId],
      );
      await client.query(
        "INSERT INTO customers(id,organization_id,external_id,channel,created_at) VALUES(501,$1,'inactive-stage-history','Organico','2026-06-01T00:00:00Z')",
        [organizationId],
      );
      await client.query(
        "INSERT INTO events(organization_id,customer_id,stage_id,occurred_at) VALUES($1,501,'visit','2026-06-01T00:00:00Z'),($1,501,'custom_demo','2026-06-02T00:00:00Z')",
        [organizationId],
      );
    } finally {
      client.release();
    }

    const input = {
      externalId: "inactive-stage-history",
      channel: "Social",
      createdAt: "2026-06-01",
      events: [
        { stage: "visit", occurredAt: "2026-06-01" },
        { stage: "custom_demo", occurredAt: "2026-06-02" },
      ],
    };
    const updated = await updatePostgresCustomer(pool!, organizationId, "501", input);
    expect(updated.channel).toBe("Social");

    await expect(updatePostgresCustomer(pool!, organizationId, "501", {
      ...input,
      events: [
        { stage: "visit", occurredAt: "2026-06-01" },
        { stage: "custom_demo", occurredAt: "2026-06-03" },
      ],
    })).rejects.toThrow("Le fasi e le date del percorso non sono valide.");

    const history = await pool!.query<{stage_id:string;occurred_at:string}>(
      "SELECT stage_id,to_char(occurred_at AT TIME ZONE 'UTC','YYYY-MM-DD') AS occurred_at FROM events WHERE organization_id=$1::uuid AND customer_id=501 ORDER BY occurred_at",
      [organizationId],
    );
    expect(history.rows).toEqual([
      { stage_id: "visit", occurred_at: "2026-06-01" },
      { stage_id: "custom_demo", occurred_at: "2026-06-02" },
    ]);
  });

});