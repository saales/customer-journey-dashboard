import { afterAll,describe,expect,it } from "vitest";
import { Pool } from "pg";
import {importPostgresCustomers} from "../src/postgres-import-repository.js";
const cs=process.env.DATABASE_URL;
const pool=cs?new Pool({connectionString:cs,max:1,connectionTimeoutMillis:5000}):null;
afterAll(async()=>{await pool?.end();});
describe("Importazione PostgreSQL tenant-scoped",()=>{
 it.skipIf(!pool)("importa atomicamente clienti, eventi, batch e audit log; blocca duplicati",async()=>{
  const org="aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",other="bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb",user="cccccccc-cccc-4ccc-8ccc-cccccccccccc";
  const c=await pool!.connect();
  try{
   await c.query("DROP TABLE IF EXISTS pg_temp.audit_logs");
   await c.query("DROP TABLE IF EXISTS pg_temp.import_batches");
   await c.query("DROP TABLE IF EXISTS pg_temp.events");
   await c.query("DROP TABLE IF EXISTS pg_temp.customers");
   await c.query("DROP TABLE IF EXISTS pg_temp.funnel_stages");
   await c.query(`CREATE TEMP TABLE customers(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organization_id UUID NOT NULL,external_id TEXT NOT NULL,channel TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL,UNIQUE(organization_id,external_id)) ON COMMIT PRESERVE ROWS`);
   await c.query(`CREATE TEMP TABLE events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organization_id UUID NOT NULL,customer_id BIGINT NOT NULL,stage_id TEXT NOT NULL,occurred_at TIMESTAMPTZ NOT NULL) ON COMMIT PRESERVE ROWS`);
   await c.query(`CREATE TEMP TABLE funnel_stages(organization_id UUID NOT NULL,id TEXT NOT NULL,position INTEGER NOT NULL,is_active BOOLEAN NOT NULL) ON COMMIT PRESERVE ROWS`);
   await c.query(`CREATE TEMP TABLE import_batches(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organization_id UUID NOT NULL,fingerprint TEXT NOT NULL,file_name TEXT NOT NULL,customer_count INTEGER NOT NULL,row_count INTEGER NOT NULL,imported_by UUID,UNIQUE(organization_id,fingerprint)) ON COMMIT PRESERVE ROWS`);
   await c.query(`CREATE TEMP TABLE audit_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organization_id UUID,actor_user_id UUID,action TEXT,resource_type TEXT,resource_id TEXT,details JSONB) ON COMMIT PRESERVE ROWS`);
   await c.query("INSERT INTO funnel_stages VALUES($1,'visit',0,true),($1,'lead',1,true),($1,'customer',2,true),($2,'visit',0,true)",[org,other]);
  }finally{c.release();}
  const rows=[
   {externalId:"crm-1",channel:"Organico",createdAt:"2026-01-01",stage:"visit",occurredAt:"2026-01-01"},
   {externalId:"crm-1",channel:"Organico",createdAt:"2026-01-01",stage:"lead",occurredAt:"2026-01-02"},
   {externalId:"crm-2",channel:"Social",createdAt:"2026-01-03",stage:"visit",occurredAt:"2026-01-03"},
  ];
  const result=await importPostgresCustomers(pool!,org,user,"clienti.csv",rows);
  expect(result).toMatchObject({importedCustomers:2,importedRows:3,importedEvents:3});
  await expect(importPostgresCustomers(pool!,org,user,"rinominato.csv",rows)).rejects.toThrow("Questo contenuto è già stato importato.");
  const otherResult=await importPostgresCustomers(pool!,other,user,"clienti.csv",[{
   externalId:"crm-1",channel:"Organico",createdAt:"2026-01-01",stage:"visit",occurredAt:"2026-01-01"
  }]);
  expect(otherResult.importedCustomers).toBe(1);
  const counts=await pool!.query<{customers:string;events:string;batches:string;audits:string}>(
   `SELECT (SELECT COUNT(*) FROM customers WHERE organization_id=$1)::text AS customers,
    (SELECT COUNT(*) FROM events WHERE organization_id=$1)::text AS events,
    (SELECT COUNT(*) FROM import_batches WHERE organization_id=$1)::text AS batches,
    (SELECT COUNT(*) FROM audit_logs WHERE organization_id=$1)::text AS audits`,[org]);
  expect(counts.rows[0]).toEqual({customers:"2",events:"3",batches:"1",audits:"1"});
 });
 it("rifiuta dati non validi prima della connessione",async()=>{
  const noConnect={connect:()=>{throw new Error("non deve connettersi");}};
  await expect(importPostgresCustomers(noConnect,"bad","bad","file.csv",[])).rejects.toThrow("Contesto utente");
 });
});
